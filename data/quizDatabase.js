/** Total soal per kategori (dipakai admin stats). */
export function countQuestions() {
  let total = 0;
  const per = {};
  for (const [cat, levels] of Object.entries(quizDatabase)) {
    per[cat] = Object.values(levels).reduce((n, arr) => n + arr.length, 0);
    total += per[cat];
  }
  return { total, per };
}