export function getToolHref(tool) {
  if (!tool) return '/';
  if (tool.href) return tool.href;
  if (tool.slug === 'downloader') return '/downloader';
  return `/tools/${tool.slug}`;
}

export function findTool(slug) {
  return featuredTools.find((t) => t.slug === slug) || null;
}
